export const formatRent = (value: number) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(value);

export const shortRent = (value: number) =>
  value >= 100000 ? `${(value / 100000).toFixed(1)}L` : `${Math.round(value / 1000)}k`;
